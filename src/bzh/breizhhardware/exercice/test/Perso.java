    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:    
    int choix = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Êtes-vous sûr de vouloir ajouter cette personne ?",
        "Confirmation",
        javax.swing.JOptionPane.YES_NO_OPTION
    );
    if (choix != javax.swing.JOptionPane.YES_OPTION) return;
    // récupérer le contenu des champs
    String idText = TxtID.getText();
    String nom = TxtNom.getText();
    String prenom = TxtPrenom.getText();
    String email = TxtEmail.getText();
    String telephone = TxtTelephone.getText();

    // vérifier que les champs ne sont pas vides
    if (idText.isEmpty() || nom.isEmpty() || prenom.isEmpty() || email.isEmpty() || telephone.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !");
        return;
    }

    // convertir l'ID en entier
    int id;
    try {
        id = Integer.parseInt(idText);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "L'ID doit être un nombre !");
        return;
    }

    try {
        Connection con = DriverManager.getConnection(
        "jdbc:mysql://localhost:3306/personnel", "root", "root");

        String sql = "INSERT INTO perso (idPerso, Nom, Prenom, email, Telephone) VALUES (?, ?, ?, ?, ?)";
        java.sql.PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, id);
        pst.setString(2, nom);
        pst.setString(3, prenom);
        pst.setString(4, email);
        pst.setString(5, telephone);

        pst.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this, "Personne ajoutée !");

        // vider les champs
        TxtID.setText("");
        TxtNom.setText("");
        TxtPrenom.setText("");
        TxtEmail.setText("");
        TxtTelephone.setText("");

        con.close();

        } catch(Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erreur : " + ex.getMessage());
        }
        loadTable();

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int choix = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Êtes-vous sûr de vouloir modifier cette personne ?",
        "Confirmation",
        javax.swing.JOptionPane.YES_NO_OPTION
        );
        if (choix != javax.swing.JOptionPane.YES_OPTION) return;
        String idText = TxtID.getText();
        String nom = TxtNom.getText();
        String prenom = TxtPrenom.getText();
        String email = TxtEmail.getText();
        String telephone = TxtTelephone.getText();

        // Vérifier que les champs ne sont pas vides
        if(idText.isEmpty() || nom.isEmpty() || prenom.isEmpty() || email.isEmpty() || telephone.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !");
            return;
        }

        // Convertir l'ID en entier
        int id;
        try {
            id = Integer.parseInt(idText);
        } catch(NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "L'ID doit être un nombre !");
            return;
        }

        // 2️⃣ Modifier la ligne dans la base
        try {
            Connection con = Database.getConnection();

            String sql = "UPDATE perso SET nom=?, prenom=?, email=?, telephone=? WHERE idPerso=?";
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            pst.setString(1, nom);
            pst.setString(2, prenom);
            pst.setString(3, email);
            pst.setString(4, telephone);
            pst.setInt(5, id);

            int rowsUpdated = pst.executeUpdate();

            if(rowsUpdated > 0){
                javax.swing.JOptionPane.showMessageDialog(this, "Personne modifiée !");
                loadTable(); // rafraîchir la JTable pour voir les changements
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "ID introuvable !");
            }

            con.close();

        } catch(Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erreur : " + ex.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

