    private void OkButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_OkButtonActionPerformed
        String login = TxtLogin.getText();
        String password = new String(TxtPassword.getPassword());
        
        if (login.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs !");
        return;
    }
        try {
        Connection con = Database.getConnection();
        String sql = "SELECT * FROM authentification WHERE login=? AND password=?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, login);
        pst.setString(2, password);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            
            // Ouvrir la fenêtre principale (perso)
            new Perso().setVisible(true);
            this.dispose(); // Ferme la fenêtre de login
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Login ou mot de passe incorrect !");
        }

        con.close();
        } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erreur : " + ex.getMessage());
        }
    }//GEN-LAST:event_OkButtonActionPerformed

